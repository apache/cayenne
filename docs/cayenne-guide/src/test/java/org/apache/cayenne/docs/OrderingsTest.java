package org.apache.cayenne.docs;

import org.apache.cayenne.docs.persistent.Painting;
import org.apache.cayenne.query.ObjectSelect;
import org.apache.cayenne.query.Ordering;
import org.apache.cayenne.query.SortOrder;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;

public class OrderingsTest extends BaseTest {

    @Test
    public void create() {
        // tag::create[]
        Ordering o1 = new Ordering("paintingTitle", SortOrder.ASCENDING);

        // the same ordering created from a property generated by Cayenne
        Ordering o2 = Painting.PAINTING_TITLE.asc();
        // end::create[]

        assertEquals(o1, o2);
    }

    @Test
    public void orderList() {
        createArtistsDataSet();

        // tag::orderList[]
        Ordering o = Painting.PAINTING_TITLE.ascInsensitive();
        List<Painting> list = ObjectSelect.query(Painting.class).select(context);
        o.orderList(list);
        // end::orderList[]

        assertEquals("Gertrude Stein", list.get(0).getPaintingTitle());
    }
}
