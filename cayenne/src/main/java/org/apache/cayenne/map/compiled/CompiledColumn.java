package org.apache.cayenne.map.compiled;


/**
 * A compiled column of a {@link CompiledTable table}. Columns are compared by identity, as two tables may have
 * columns of the same name.
 *
 * @since 6.0
 */
public final class CompiledColumn {

    private final String name;
    private final int jdbcType;
    private final int maxLength;
    private final int scale;
    private final int precision;
    private final boolean mandatory;
    private final boolean primaryKey;
    private final boolean generated;
    private final String valueClassName;

    // written once by the compiler, when the owning table is created
    CompiledTable table;

    CompiledColumn(
            String name,
            int jdbcType,
            int maxLength,
            int scale,
            int precision,
            boolean mandatory,
            boolean primaryKey,
            boolean generated,
            String valueClassName) {

        this.name = name;
        this.jdbcType = jdbcType;
        this.maxLength = maxLength;
        this.scale = scale;
        this.precision = precision;
        this.mandatory = mandatory;
        this.primaryKey = primaryKey;
        this.generated = generated;
        this.valueClassName = valueClassName;
    }

    public String name() {
        return name;
    }

    /**
     * Returns the table of this column.
     */
    public CompiledTable table() {
        return table;
    }

    /**
     * Returns the JDBC type of the column.
     *
     * @see java.sql.Types
     */
    public int jdbcType() {
        return jdbcType;
    }

    /**
     * Returns the length of a character or binary column, or the max number of digits of a decimal, or -1 if not
     * set.
     */
    public int maxLength() {
        return maxLength;
    }

    /**
     * Returns the number of digits after the period of a decimal column, or -1 if not set.
     */
    public int scale() {
        return scale;
    }

    public int precision() {
        return precision;
    }

    public boolean isMandatory() {
        return mandatory;
    }

    public boolean isPrimaryKey() {
        return primaryKey;
    }

    /**
     * Returns true if the column value is generated by the database, i.e. it is an "auto-increment" or an "identity"
     * column.
     */
    public boolean isGenerated() {
        return generated;
    }

    /**
     * Returns the name of the Java class the values of the column are read as, derived from its JDBC type.
     */
    public String valueClassName() {
        return valueClassName;
    }

    @Override
    public String toString() {
        return (table != null ? table.name() + "." : "") + name;
    }
}
